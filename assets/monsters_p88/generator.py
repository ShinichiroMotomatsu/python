from PIL import Image, ImageDraw, ImageFont
import os, math

PAL = {
 'navy': (20, 22, 40, 255), 'blue': (48, 80, 180, 255), 'lblue': (130, 180, 232, 255),
 'cream': (232, 226, 192, 255), 'dgreen': (30, 100, 52, 255), 'green': (106, 180, 70, 255),
 'brown': (160, 106, 44, 255), 'red': (204, 70, 50, 255),
}
S = 128

def new():
    return Image.new('RGBA', (S, S), (0, 0, 0, 0))
def E(d, box, c): d.ellipse(box, fill=PAL[c])
def P(d, pts, c): d.polygon(pts, fill=PAL[c])
def R(d, box, c): d.rectangle(box, fill=PAL[c])
def L(d, pts, c, w=1): d.line(pts, fill=PAL[c], width=w)
def A(d, box, a0, a1, c, w=1): d.arc(box, a0, a1, fill=PAL[c], width=w)

def dith(img, box, cfrom, cto, lvl):
    """box内で色cfromのピクセルをctoへ (lvl:1=1/8 2=1/4 3=1/2)"""
    px = img.load()
    fx, fy, tx, ty = box
    for y in range(max(0, fy), min(S, ty + 1)):
        for x in range(max(0, fx), min(S, tx + 1)):
            if px[x, y] != PAL[cfrom]: continue
            if lvl == 1: hit = (x % 4 == 1 and y % 4 == 1) or (x % 4 == 3 and y % 4 == 3)
            elif lvl == 2: hit = (x % 2 == 0 and y % 2 == 0)
            else: hit = (x + y) % 2 == 0
            if hit: px[x, y] = PAL[cto]

def outline(img):
    px = img.load(); edge = []
    for y in range(S):
        for x in range(S):
            if px[x, y][3] != 0: continue
            for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
                nx, ny = x+dx, y+dy
                if 0 <= nx < S and 0 <= ny < S and px[nx, ny][3] != 0 and px[nx, ny] != PAL['navy']:
                    edge.append((x, y)); break
    for x, y in edge: px[x, y] = PAL['navy']

